"""Generate THIRD_PARTY_NOTICES.md from what is actually installed: Python packages the product depends on
(engine, server, research core) and the web app's production npm packages. Run from the repository root:
    python3 deploy/make_notices.py > THIRD_PARTY_NOTICES.md
Needs pip-licenses and (for the web app) a built node_modules: `pip install pip-licenses`, `cd frontend && npm ci`."""

import json
import re
import subprocess
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROOTS = ["cardiotic-server", "cardiotic-engine", "cardiotic-ml"]


def py_closure() -> set[str]:
    """Runtime dependencies of the three product packages (read from their pyproject.toml, not from stale install metadata)."""
    import tomllib
    seen, todo = set(), []
    for pkg in ("ml", "engine", "server"):
        todo += tomllib.loads((ROOT / pkg / "pyproject.toml").read_text())["project"]["dependencies"]
    while todo:
        n = re.split(r"[<>=!~\[; ]", todo.pop().lower().replace("_", "-"))[0]
        if n in seen or n.startswith("cardiotic"):
            continue
        try:
            d = metadata.distribution(n)
        except metadata.PackageNotFoundError:
            print(f"warning: {n} is not installed; its licence is missing", file=sys.stderr)
            continue
        seen.add(n)
        todo += [r for r in (d.requires or []) if "extra ==" not in r]
    return seen


def licence_of(d: metadata.Distribution) -> str:
    m = d.metadata
    lic = (m.get("License-Expression") or "").strip()
    if not lic:
        cls = [c.split("::")[-1].strip() for c in m.get_all("Classifier") or [] if c.startswith("License ::") and "OSI Approved" in c]
        lic = "; ".join(cls) if cls else (m.get("License") or "").strip().splitlines()[0][:80] if (m.get("License") or "").strip() else "see package"
    return lic


def main() -> None:
    out = ["# Third-party notices", "",
           "Cardiotic AI includes the open-source software below. Each package is used under its own licence; "
           "the licence texts are in the packages themselves (the container's `site-packages/*/licenses` folders and "
           "the web app's bundled licence comments). This file is generated by `deploy/make_notices.py`.", "",
           "**Copyleft notice:** `ldap3` is licensed under the GNU LGPL v3. It is used unmodified as a separate library "
           "(imported at run time); you may replace it with another version of the library.", "",
           "## Python packages", "", "| Package | Version | Licence |", "|---|---|---|"]
    rows = []
    for n in sorted(py_closure() - {"cardiotic-server", "cardiotic-engine", "cardiotic-ml"}):
        d = metadata.distribution(n)
        rows.append((d.metadata["Name"], d.version, licence_of(d).replace("|", "/")))
    out += [f"| {a} | {b} | {c} |" for a, b, c in rows]
    out += ["", "## Web app (production npm packages)", "", "| Package | Version | Licence |", "|---|---|---|"]
    try:
        raw = subprocess.run(["npx", "--yes", "license-checker", "--production", "--json", "--start", str(ROOT / "frontend")],
                             capture_output=True, text=True, check=True, timeout=600).stdout
        pk = json.loads(raw)
        for k in sorted(pk):
            if k.startswith("cardiotic") or "frontend@" in k:
                continue
            name, _, ver = k.rpartition("@")
            out.append(f"| {name} | {ver} | {str(pk[k].get('licenses', '')).replace('|', '/')} |")
    except Exception as e:  # noqa: BLE001
        out.append(f"| (could not read npm licences: {str(e)[:60]}) | | |")
    out += ["", "## Fonts and data", "",
            "The web app bundles a font under the SIL Open Font License 1.1. The statement catalogue uses the SCP-ECG code names (public standard). "
            "Models were trained on public research datasets; their terms are recorded in `docs/03_MANAGEMENT_ACTIONS.md` and the model cards.", ""]
    sys.stdout.write("\n".join(out))


main()
